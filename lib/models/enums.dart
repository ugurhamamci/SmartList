/// Unit of measure attached to an item quantity.
@JsonEnum(valueField: 'wire')
enum MeasurementUnit {
  piece('piece'),
  gram('g'),
  kilogram('kg'),
  milliliter('ml'),
  liter('l'),
  pack('pack'),
  box('box'),
  bottle('bottle'),
  can('can'),
  bag('bag'),
  bunch('bunch'),
  dozen('dozen'),
  ounce('oz'),
  pound('lb'),
  fluidOunce('fl_oz'),
  gallon('gal');

  const MeasurementUnit(this.wire);

  final String wire;

  static MeasurementUnit fromWire(String? value) {
    for (final unit in MeasurementUnit.values) {
      if (unit.wire == value) {
        return unit;
      }
    }
    return MeasurementUnit.piece;
  }

  bool get isMetric => const {
    MeasurementUnit.gram,
    MeasurementUnit.kilogram,
    MeasurementUnit.milliliter,
    MeasurementUnit.liter,
  }.contains(this);

  bool get isImperial => const {
    MeasurementUnit.ounce,
    MeasurementUnit.pound,
    MeasurementUnit.fluidOunce,
    MeasurementUnit.gallon,
  }.contains(this);
}

