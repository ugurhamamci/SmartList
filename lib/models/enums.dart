/// Collaboration role held by a member of a shopping list.
///
/// The wire values are mirrored by `firestore.rules`; renaming one requires a
/// rules change and a data migration.
@JsonEnum(valueField: 'wire')
enum MemberRole {
  owner('owner', 3),
  editor('editor', 2),
  viewer('viewer', 1),
  guest('guest', 0);

  const MemberRole(this.wire, this.rank);

  final String wire;

  /// Higher rank implies strictly more capability.
  final int rank;

  static MemberRole fromWire(String? value) {
    for (final role in MemberRole.values) {
      if (role.wire == value) {
        return role;
      }
    }
    return MemberRole.guest;
  }

  bool get isOwner => this == MemberRole.owner;

  /// Owners and editors may mutate list content.
  bool get canEditItems => rank >= MemberRole.editor.rank;

  /// Owners, editors and viewers may tick items off.
  bool get canCompleteItems => rank >= MemberRole.viewer.rank;

  /// Only owners may delete or transfer a list.
  bool get canDeleteList => isOwner;

  bool get canManageMembers => isOwner;

  /// Guests observe the conversation without contributing.
  bool get canSendMessages => rank >= MemberRole.viewer.rank;

  bool get canInvite => rank >= MemberRole.editor.rank;

  bool atLeast(MemberRole other) => rank >= other.rank;
}

